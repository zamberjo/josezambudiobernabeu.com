import { disassemblePortfolio } from '@jzb/application';
import { COLLECTIONS, SITE_SECTIONS, type CollectionName, type Portfolio } from '@jzb/domain';
import { codecs } from './codecs.ts';

/*
 * Turns a snapshot into the SQL that recreates it: the seed for
 * `supabase db reset`, and the first load of a new remote project. It goes
 * through the same codecs as the live adapter, so a seeded database reads back
 * as exactly the snapshot it came from.
 */

const quote = (text: string) => `'${text.replaceAll("'", "''")}'`;

/** A Postgres literal for a codec's column value. Pure; no driver needed. */
export const sqlLiteral = (value: unknown): string => {
	if (value === null || value === undefined) return 'null';
	if (typeof value === 'boolean' || typeof value === 'number') return String(value);
	if (typeof value === 'string') return quote(value);
	if (Array.isArray(value) && value.every((item) => typeof item === 'string'))
		return value.length === 0 ? `'{}'::text[]` : `array[${value.map(quote).join(', ')}]::text[]`;
	return `${quote(JSON.stringify(value))}::jsonb`;
};

const insert = (table: string, rows: Record<string, unknown>[]): string => {
	if (rows.length === 0) return `-- ${table}: empty\n`;
	const columns = Object.keys(rows[0]!);
	const values = rows
		.map((row) => `  (${columns.map((column) => sqlLiteral(row[column])).join(', ')})`)
		.join(',\n');
	return `insert into public.${table} (${columns.join(', ')}) values\n${values};\n`;
};

export const seedSql = (portfolio: Portfolio): string => {
	const { sections, lists } = disassemblePortfolio(portfolio);

	const collectionRows = <K extends CollectionName>(collection: K) =>
		(lists[collection] as { position: number; data: Portfolio[K][number] }[]).map(
			({ position, data }) => ({
				position,
				...(codecs[collection].toRow as (entity: unknown) => Record<string, unknown>)(data)
			})
		);

	return [
		'-- Generated by `pnpm content:seed` from content/portfolio.json. Do not edit by hand.\n',
		insert(
			'site_sections',
			SITE_SECTIONS.map((key) => ({ key, value: sections[key] }))
		),
		...COLLECTIONS.map((collection) => insert(collection, collectionRows(collection)))
	].join('\n');
};
